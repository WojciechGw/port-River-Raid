"""Pack the readable sound icons in graphics.h into one bit per pixel."""
import argparse
import re
from pathlib import Path


def pack(source):
    body = source.split("static const char sound_icons", 1)[1].split("};", 1)[0]
    rows = re.findall(r'"([^"\n]*)"', body)
    if len(rows) != 16:
        raise ValueError(f"sound_icons: expected 16 rows (two 8x8 icons), got {len(rows)}")
    for i, row in enumerate(rows):
        where = f"sound_icons: icon {i // 8 + 1}, row {i % 8 + 1}"
        if len(row) != 8:
            raise ValueError(f"{where}: expected 8 pixels, got {len(row)}")
        for column, pixel in enumerate(row, 1):
            if pixel not in ".Xx":
                raise ValueError(f"{where}, column {column}: invalid pixel {pixel!r}; use '.', 'X' or 'x'")
    data = [int(row.upper().replace(".", "0").replace("X", "1"), 2) for row in rows]
    return (
        "/* Generated by tools/pack_sound_icons.py; edit src/graphics.h. */\n"
        "const uint8_t sound_icons[2][8] = {\n"
        + ",\n".join("    {" + ",".join(f"0x{v:02x}" for v in data[i:i+8]) + "}"
                     for i in (0, 8))
        + "\n};\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(pack(args.source.read_text(encoding="utf-8")), encoding="utf-8")
