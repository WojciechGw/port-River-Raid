"""Pack the readable mountain bitmaps in graphics.h into two bits per pixel."""
import argparse
import re
from pathlib import Path


def pack(source):
    body = source.split("static const char mountain_pixels", 1)[1].split("};", 1)[0]
    rows = re.findall(r'"([.BKU]+)"', body)
    if len(rows) != 5 * 21 or any(len(row) != 32 for row in rows):
        raise ValueError("Expected five 32 x 21 mountain bitmaps")
    data = []
    for row in rows:
        for x in range(0, 32, 4):
            value = 0
            for pixel in row[x:x+4]:
                value = value * 4 + ".BKU".index(pixel)
            data.append(value)
    return "/* Generated by tools/pack_mountains.py; edit src/graphics.h. */\n" + \
        "static const uint8_t mountain_packed[5][21][8] = {\n" + \
        ",\n".join("    {" + ",\n     ".join(
            "{" + ",".join(f"0x{v:02x}" for v in data[i:i+8]) + "}"
            for i in range(start, start+168, 8)) + "}"
            for start in range(0, len(data), 168)) + "\n};\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(pack(args.source.read_text(encoding="utf-8")), encoding="utf-8")
