"""Build the readable demo caption and existing Activision logo into XRAM pixels.

One logical pixel spans two canvas pixels, encoded as equal 4bpp nibbles.
Text uses the light-gray lettering entry (2) in the demo footer palette.
Every text cell contains a 6x7 glyph followed by two transparent columns.
The logo is padded to whole eight-pixel cells; the strip spans six 160-pixel screens.
The strip is rendered at build time; gameplay only changes its VGA position.
"""
import argparse
import json
import re
from pathlib import Path

GLYPH_WIDTH = 6
GLYPH_HEIGHT = 7
CELL_WIDTH = 8
SCROLLER_WIDTH = 160*6


def build(source, graphics, duo=False):
    caption = json.loads(source.read_text(encoding="utf-8"))
    if caption["advance"] != CELL_WIDTH or caption["space_advance"] != CELL_WIDTH:
        raise ValueError("Every caption cell must be 8 pixels: a 6-pixel glyph plus 2 pixels of spacing")
    for char, glyph in caption["font"].items():
        if len(glyph) != GLYPH_HEIGHT or any(
                len(row) != GLYPH_WIDTH or set(row)-set(".X") for row in glyph):
            raise ValueError(f"Caption glyph must be exactly 6x7: {char}")
    match = re.search(r"activision_logo\[8\]\[\d+\]\s*=\s*\{(.*?)\};",
                      graphics.read_text(encoding="utf-8"), re.S)
    if not match:
        raise ValueError("Cannot find the reference Activision bitmap")
    logo = re.findall(r'"([.A-F]+)"', match[1])
    if len(logo) != 8 or not logo[0] or any(len(row) != len(logo[0]) for row in logo):
        raise ValueError("Expected eight equally wide Activision logo rows")
    logo_width = (len(logo[0])+CELL_WIDTH-1)//CELL_WIDTH*CELL_WIDTH
    rows = [bytearray() for _ in range(8)]
    text = caption["text"]
    while text:
        if text.startswith("{Activision}"):
            for y, pixels in enumerate(logo):
                rows[y].extend(0 if p == "." else (ord(p)-ord("A")+1)*17 for p in pixels)
                rows[y].extend(bytes(logo_width-len(pixels)))
            text = text[len("{Activision}"):]
            continue
        char, text = text[0], text[1:]
        if char == " ":
            glyph = ["."*GLYPH_WIDTH]*GLYPH_HEIGHT
        else:
            glyph = caption["font"][char]
        for y, row in enumerate(rows):
            pixels = glyph[y-1] if y else "."*GLYPH_WIDTH
            row.extend(0x22 if p == "X" else 0 for p in pixels)
            row.extend(bytes(CELL_WIDTH-GLYPH_WIDTH))
    width = len(rows[0])
    if width > SCROLLER_WIDTH:
        raise ValueError(f"Caption is {width} pixels wide; maximum is {SCROLLER_WIDTH}")
    for row in rows:
        row.extend(bytes(SCROLLER_WIDTH-width))
    return SCROLLER_WIDTH*2, b"".join(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("graphics", type=Path)
    parser.add_argument("image", type=Path)
    parser.add_argument("header", type=Path)
    parser.add_argument("duo_image", type=Path)
    args = parser.parse_args()
    width, data = build(args.source, args.graphics)
    args.image.parent.mkdir(parents=True, exist_ok=True)
    args.image.write_bytes(data)
    duo_width, duo_data = build(args.source, args.graphics, duo=True)
    args.duo_image.write_bytes(duo_data)
    args.header.write_text(
        "/* Generated by tools/make_demo_footer.py; edit src/demo-footer.json. */\n"
        f"#define DEMO_FOOTER_LOGICAL_WIDTH {SCROLLER_WIDTH}\n"
        f"#define DEMO_FOOTER_WIDTH {width}\n#define DEMO_FOOTER_BYTES {len(data)}\n"
        f"#define DUO_DEMO_FOOTER_WIDTH {duo_width}\n#define DUO_DEMO_FOOTER_BYTES {len(duo_data)}\n",
        encoding="utf-8")


if __name__ == "__main__":
    main()
