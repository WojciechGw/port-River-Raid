"""Build the readable demo caption and existing Activision logo into XRAM pixels.

One logical pixel spans two canvas pixels, encoded as equal 4bpp nibbles.
Text uses the light-gray lettering entry (2) in the demo footer palette.
Six-column glyphs, the seven-column w and raised TM follow the Atari caption font.
The strip is rendered at build time; gameplay only changes its VGA position.
"""
import argparse
import json
import re
from pathlib import Path


def build(source, graphics):
    caption = json.loads(source.read_text(encoding="utf-8"))
    match = re.search(r"activision_logo\[8\]\[61\]\s*=\s*\{(.*?)\};",
                      graphics.read_text(encoding="utf-8"), re.S)
    if not match:
        raise ValueError("Cannot find the reference Activision bitmap")
    logo = re.findall(r'"([.A-F]+)"', match[1])
    if len(logo) != 8 or any(len(row) != 60 for row in logo):
        raise ValueError("Expected the original 60x8 logo")
    rows = [bytearray() for _ in range(8)]
    text = caption["text"]
    while text:
        if text.startswith("{Activision}"):
            for y, pixels in enumerate(logo):
                rows[y].extend(0 if p == "." else (ord(p)-ord("A")+1)*17 for p in pixels)
            text = text[len("{Activision}"):]
            continue
        char, text = text[0], text[1:]
        if char == " ":
            glyph, top, width = [], 0, caption["space_advance"]
        else:
            glyph = caption["trademark"] if char == "™" else caption["font"][char]
            top = 0 if char == "™" else 1
            height, widths = (5, (9,)) if char == "™" else (7, (6, 7))
            glyph_width = len(glyph[0])
            if len(glyph) != height or glyph_width not in widths or any(
                    len(row) != glyph_width or set(row)-set(".X") for row in glyph):
                raise ValueError(f"Invalid glyph: {char}")
            width = caption["trademark_advance"] if char == "™" else caption["advance"]
            if width < glyph_width:
                raise ValueError(f"Glyph advance is too narrow: {char}")
        for y, row in enumerate(rows):
            pixels = glyph[y-top] if top <= y < top+len(glyph) else "."*(width-1)
            row.extend(0x22 if p == "X" else 0 for p in pixels)
            row.extend(bytes(width-len(pixels)))
    width = len(rows[0])
    if width < 160 or width*8 > 0x8000-0x3800:
        raise ValueError("Demo caption does not fit its XRAM region")
    return width*2, b"".join(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("graphics", type=Path)
    parser.add_argument("image", type=Path)
    parser.add_argument("header", type=Path)
    args = parser.parse_args()
    width, data = build(args.source, args.graphics)
    args.image.parent.mkdir(parents=True, exist_ok=True)
    args.image.write_bytes(data)
    args.header.write_text(
        "/* Generated by tools/make_demo_footer.py; edit src/demo-footer.json. */\n"
        f"#define DEMO_FOOTER_WIDTH {width}\n#define DEMO_FOOTER_BYTES {len(data)}\n",
        encoding="utf-8")


if __name__ == "__main__":
    main()
